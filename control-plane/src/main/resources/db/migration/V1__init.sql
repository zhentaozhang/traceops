-- TraceOps 控制面的初始 schema。
--
-- 这份文件是**唯一**的建表来源：`spring.jpa.hibernate.ddl-auto` 默认是
-- `validate`，应用启动时只做校验，不会建表、更不会删表。想改表结构就加一个
-- V2__xxx.sql，改完启动会告诉你实体与脚本是否还对得上。
--
-- 目标方言：H2（P0 的运行数据库，内存或文件）。PostgreSQL 适配未验证，
-- 因此这里不提供 Postgres 专用脚本 —— 见 设计决策 的 R-15。

create table incidents (
    id varchar(255) not null,
    fingerprint varchar(255),
    service varchar(255),
    title varchar(255),
    severity varchar(255),
    origin enum ('ALERT','MANUAL'),
    status enum ('NEW','INVESTIGATING','DIAGNOSED','RESOLVED','FAILED'),
    created_at timestamp(6) with time zone,
    updated_at timestamp(6) with time zone,
    investigation_window_start timestamp(6) with time zone,
    investigation_window_end timestamp(6) with time zone,
    retry_attempts integer not null,
    current_run_id varchar(255),
    next_retry_at timestamp(6) with time zone,
    unavailable_sources varchar(255),
    duplicate_alerts integer not null,
    version bigint not null,
    primary key (id)
);

create table outbox_events (
    event_id varchar(255) not null,
    event_type varchar(255),
    aggregate_id varchar(255),
    aggregate_version bigint not null,
    payload clob not null,
    created_at timestamp(6) with time zone,
    not_before timestamp(6) with time zone,
    published_at timestamp(6) with time zone,
    attempts integer not null,
    primary key (event_id)
);

create index ix_outbox_pending on outbox_events (published_at, created_at);
create index ix_outbox_not_before on outbox_events (published_at, not_before);

create table applied_investigation_events (
    event_id varchar(255) not null,
    investigation_run_id varchar(255) not null,
    event_type varchar(255) not null,
    incident_id varchar(255),
    outcome varchar(255) not null,
    previous_status varchar(255),
    resulting_status varchar(255),
    reason varchar(500),
    applied_at timestamp(6) with time zone not null,
    primary key (event_id),
    constraint uk_applied_run_id unique (investigation_run_id)
);

create table investigation_findings (
    incident_id varchar(255) not null,
    investigation_run_id varchar(255),
    diagnosis_status varchar(255),
    abstained boolean not null,
    needs_human_review boolean not null,
    root_cause_service varchar(255),
    root_cause_component varchar(255),
    root_cause_fault_type varchar(255),
    affected_services clob,
    root_cause_candidates_json clob,
    propagation_chain_json clob,
    evidence_total integer not null,
    tool_calls integer not null,
    tokens_used integer not null,
    report_ref varchar(255),
    updated_at timestamp(6) with time zone,
    primary key (incident_id)
);

create table investigation_finding_history (
    id bigint generated by default as identity,
    incident_id varchar(255) not null,
    investigation_run_id varchar(255) not null,
    diagnosis_status varchar(255),
    abstained boolean not null,
    root_cause_service varchar(255),
    root_cause_fault_type varchar(255),
    evidence_total integer not null,
    tool_calls integer not null,
    tokens_used integer not null,
    root_cause_candidates_json clob,
    recorded_at timestamp(6) with time zone not null,
    primary key (id)
);

create index ix_finding_history_incident on investigation_finding_history (incident_id, recorded_at);

create table investigation_progress (
    run_id varchar(255) not null,
    current_node varchar(255),
    step_index integer not null,
    step_description varchar(1000),
    evidence_count integer not null,
    updated_at timestamp(6) with time zone not null,
    primary key (run_id)
);
