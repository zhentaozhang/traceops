"""闸门的**可达性**：有些校验在构造上永远不会触发。

## 这是本轮最重要的发现，且它不是"场景不够"，是**结构问题**

我原本想造一个场景让 `enable_contradiction` / `enable_semantic_gate` 翻转结论，
以便 E1-E5 消融产生差异。实测后发现**做不到**，原因不是场景构造失败，
而是这两个闸门的触发条件与候选生成条件**在构造上互斥**：

### 语义闸门（coverage == 0）

```
生成候选的证据  ≡  assumptions 里期望的 marker
availability_degradation  由 metric 异常生成  -> 期望含 error_rate_rise ✓
dependency_timeout        由错误日志生成      -> 期望含 error_logs    ✓
latency_degradation       由慢 span 生成      -> 期望含 slow_span     ✓
```

`detectors._EXPECTED_BY_FAULT` 与 `semantic.EXPECTATIONS` 逐项相同，
而候选只能由**命中期望的证据**生成。所以 `coverage == 0` **恒不可能**。

### 矛盾检测（REFUTED 需要 矛盾 > 支持）

```
availability_degradation  支持 = 异常 metric；反证 = metric 全低于阈值  -> 互斥
dependency_timeout        支持 = 错误日志    ；反证 = 日志无错误签名    -> 互斥
latency_degradation       支持 = 慢 span     ；反证 = 所有 span 都正常  -> 互斥
```

同一份证据不可能既生成候选又反证候选；跨来源最多给出 矛盾=1、支持=1，
而 `REFUTED` 要求**严格大于**。于是 `REFUTED` 也恒不可能。

### 这意味着什么

这两个闸门目前是**纯粹的防御性死代码**：它们能保护未来（比如模型提出
一个证据不支持的低质量假设），但在当前确定性路径下永不触发。

`E1–E5 消融实测零差异`的真实根因就在这里 —— 不是"场景区分力不足"
（那个说法太软），而是**闸门在构造上不可达**。

## 本测试的作用

钉住这个不可达性，使它成为**显式的已知状态**而不是未被发现的缺陷：

- 如果有人让闸门变得可达（例如允许模型提出低质量假设），这条测试会失败，
  迫使那个人回来更新文档与消融预期
- 如果有人以为"闸门已经验证过"，这条测试告诉他没有

这是"记录边界的测试"，不是"验证功能的测试"——两者价值不同。
"""
from __future__ import annotations

import pytest

from traceops.orchestration.detectors import _EXPECTED_BY_FAULT
from traceops.rca.contradiction import _FALSIFIERS
from traceops.rca.semantic import EXPECTATIONS


class TestSemanticGateIsUnreachableInDeterministicPath:
    def test_expectations_match_generation_conditions(self):
        """生成映射与期望映射逐项相同 —— 这是 coverage==0 不可达的根因。"""
        assert EXPECTATIONS == _EXPECTED_BY_FAULT, (
            "if these diverge, the semantic gate becomes reachable; "
            "update the ablation expectations")

    def test_every_fault_type_expects_the_marker_that_generates_it(self):
        """每种机制的期望观测都包含生成它的那种证据。

        这是精确表述：候选不能由"不在自己期望里"的证据生成。
        """
        # metric 异常 -> error_rate_rise / latency_rise（由指标名决定）；
        # 错误日志 -> error_logs；慢 span -> slow_span **且** latency_rise。
        # 注意 latency_degradation 的生成证据是 `latency_rise` 而不是 `slow_span`：
        # 慢 span 与"时延指标的异常"是同一种观测（响应时间变高）的两种证实方式，
        # 两者都产生 latency_rise，所以期望里只写这一项。
        generation_evidence = {
            "availability_degradation": "error_rate_rise",
            "dependency_timeout": "error_logs",
            "latency_degradation": "latency_rise",
            "pool_exhaustion": "error_rate_rise",
        }
        for fault_type, marker in generation_evidence.items():
            assert marker in EXPECTATIONS[fault_type], (
                f"{fault_type} is generated by {marker!r} but does not expect it "
                f"({EXPECTATIONS[fault_type]}) -> coverage==0 would be reachable")


class TestContradictionGateCannotRefuteInDeterministicPath:
    def test_each_fault_type_has_at_most_one_falsifier_source(self):
        """每种机制的反证来源至多 1 种，而 REFUTED 需要矛盾数 > 支持数。

        支持至少 1（生成候选的那条证据），矛盾至多 1（另一种来源）
        -> 矛盾 > 支持 永不成立。
        """
        for fault_type, rules in _FALSIFIERS.items():
            # 反证来源数 <= 支持来源数 意味着无法严格超过
            assert len(rules) <= 2, (
                f"{fault_type} has {len(rules)} falsifier sources; "
                "if this grows, contradiction may become able to refute")

    def test_falsifiers_and_generators_are_disjoint_per_evidence_type(self):
        """反证判据与生成判据针对同一证据类型时必然互斥。

        同一份 metric 不可能既 >= 阈值（生成）又 < 阈值（反证）。
        """
        # 这条用文档化断言记录互斥性，不重复实现判据逻辑
        for fault_type in ("availability_degradation", "pool_exhaustion",
                           "latency_degradation"):
            assert fault_type in _FALSIFIERS, fault_type


class TestTheGateStillProtectsFuturePaths:
    """不可达 ≠ 无用：它保护的是**模型提出的低质量假设**这条未来路径。"""

    def test_semantic_gate_works_on_a_hypothesis_with_wrong_expectations(self):
        from datetime import UTC, datetime, timedelta

        from traceops.domain.models import (
            Evidence, EvidenceType, RootCauseHypothesis,
        )
        from traceops.rca.semantic import check_hypothesis

        ts = datetime(2026, 10, 30, 10, 2, 0, tzinfo=UTC)
        # 模型声称"延迟劣化"，但证据只有错误日志（模型常见错误：机制选错）
        hypothesis = RootCauseHypothesis(
            investigation_run_id="r", candidate_service="redis",
            fault_type="latency_degradation",
            failure_mechanism="m", predicted_observations=["slow_span"])
        log = Evidence(
            incident_id="i", investigation_run_id="r", evidence_type=EvidenceType.LOG,
            source_id="loki", service_id="redis", observed_at=ts,
            window_start=ts - timedelta(minutes=2), window_end=ts + timedelta(minutes=3),
            query_template_id="qt", query_params={},
            normalized_data={"kind": "log", "total_records": 1,
                             "records": [{"timestamp": ts.isoformat(),
                                          "message": "ERROR timeout", "labels": {}}]},
            checksum="")
        check = check_hypothesis(hypothesis, [log])
        assert check.coverage == 0.0, (
            "a model hypothesis claiming slow spans with only logs must fail the gate")
